// Builds src/player/hanzi-data.mjs: single-character Traditional ⇄ Simplified
// tables from OpenCC's dictionaries (Apache-2.0), as shipped in opencc-js.
//
//   npm pack opencc-js@1.0.5 && tar xzf opencc-js-1.0.5.tgz
//   node scripts/generate-hanzi.mjs package/dist/esm-lib/dict
//
// Only characters are kept (no phrase tables): good enough to compare titles
// and to build search variants, and small enough for the page bundle.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/generate-hanzi.mjs <opencc-js dist/esm-lib/dict>'); process.exit(1); }
const read = (name) => {
  const text = fs.readFileSync(path.join(dir, `${name}.js`), 'utf8');
  const body = /export default "([\s\S]*)"/.exec(text)?.[1];
  if (!body) throw new Error(`unexpected format in ${name}.js`);
  const map = new Map();
  for (const entry of body.split('|')) {
    const [from, first] = entry.split(' ');
    // Characters only, first (most common) target.
    if (from && first && [...from].length === 1 && [...first].length === 1 && from !== first) map.set(from, first);
  }
  return map;
};

const ts = read('TSCharacters'), st = read('STCharacters');
const twRev = read('TWVariantsRev'), hkRev = read('HKVariantsRev'), tw = read('TWVariants');
// Traditional → Simplified: OpenCC standard forms, plus Taiwan / Hong Kong variants (為 → 爲 → 为).
const toSimplified = new Map(ts);
for (const variants of [twRev, hkRev]) for (const [variant, standard] of variants) if (!toSimplified.has(variant)) toSimplified.set(variant, ts.get(standard) || standard);
// Simplified → Traditional, written the way Taiwan storefronts and libraries do (为 → 爲 → 為).
const toTraditional = new Map([...st].map(([simplified, standard]) => [simplified, tw.get(standard) || standard]));
const pack = (map) => [...map].filter(([a, b]) => a !== b).sort(([a], [b]) => a.codePointAt(0) - b.codePointAt(0)).map(([a, b]) => a + b).join('');

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'player', 'hanzi-data.mjs');
fs.writeFileSync(out, `// Generated by scripts/generate-hanzi.mjs from OpenCC (Apache-2.0) via opencc-js (MIT).
// Pairs of characters: [from, to, from, to, ...]. Do not edit by hand.
export const T2S = ${JSON.stringify(pack(toSimplified))};
export const S2T = ${JSON.stringify(pack(toTraditional))};
`);
console.log(`wrote ${out}: ${toSimplified.size} T→S, ${toTraditional.size} S→T`);
