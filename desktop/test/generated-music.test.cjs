'use strict';
const test = require('node:test'), assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const esbuild = require('esbuild');
const { BUILDS } = require('../build-music.cjs');

test('committed music bundles match their sources (run npm run build:music)', async () => {
  for (const options of BUILDS) {
    const result = await esbuild.build({ ...options, write: false });
    const name = path.basename(options.outfile), committed = fs.readFileSync(options.outfile, 'utf8');
    assert.match(committed, /^\/\/ @generated by desktop\/build-music\.cjs/, `${name} carries the generated banner`);
    assert.equal(result.outputFiles[0].text, committed, `${name} is out of date; run npm --prefix desktop run build:music`);
  }
});
